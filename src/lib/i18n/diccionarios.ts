export const IDIOMAS = ["es", "en", "pt"] as const;
export type Idioma = (typeof IDIOMAS)[number];
export const DICCIONARIOS: Record<Idioma, Diccionario> = { es, en, pt };
export type Textos = Diccionario;

export function esIdioma(v: unknown): v is Idioma {
  return typeof v === "string" && (IDIOMAS as readonly string[]).includes(v);
}

/** Rellena marcadores {nombre} de un texto: rellenar(t["inicio.hola"], { alias: "alez" }). */
export function rellenar(texto: string, valores: Record<string, string | number>) {
  return texto.replace(/\{(\w+)\}/g, (_, k: string) => String(valores[k] ?? ""));
}
